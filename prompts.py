def get_prompt(version: str | None = None) -> PromptTemplate:
    """Return the prompt template for the given version (or active default)."""
    v = version or ACTIVE_PROMPT_VERSION
    return PROMPTS.get(v, PROMPTS[ACTIVE_PROMPT_VERSION])
